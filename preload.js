const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  getApps: () => ipcRenderer.invoke('get-apps'),
  getFavs: () => ipcRenderer.invoke('get-favs'),
  getTools: () => ipcRenderer.invoke('get-tools'),
  getToolApps: () => ipcRenderer.invoke('get-tool-apps'),
  setFavs: f => ipcRenderer.send('set-favs', f),
  launch: a => ipcRenderer.send('launch', a),
  runTool: t => ipcRenderer.send('run-tool', t),
  hide: () => ipcRenderer.send('hide'),
  toolClose: () => ipcRenderer.send('tool-close'),
  deleteTool: id => ipcRenderer.send('delete-tool', id),
  updateTool: t => ipcRenderer.send('update-tool', t),
  addTool: t => ipcRenderer.send('add-tool', t),
  importScript: () => ipcRenderer.invoke('import-script'),
  getPrefs: () => ipcRenderer.invoke('get-prefs'),
  savePrefs: p => ipcRenderer.send('save-prefs', p),
  setAnchor: a => ipcRenderer.send('set-anchor', a),
  onAnchor: cb => ipcRenderer.on('anchor-applied', (e, g) => cb(g)),
  getRecent: () => ipcRenderer.invoke('get-recent'),
  recordLaunch: item => ipcRenderer.send('record-launch', item),
  removeFromRecent: id => ipcRenderer.send('remove-from-recent', id),
  clearRecent: () => ipcRenderer.send('clear-recent'),
  openFiles: () => ipcRenderer.send('open-files'),
  suspend: () => ipcRenderer.send('action-suspend'),
  restart: () => ipcRenderer.send('action-restart'),
  poweroff: () => ipcRenderer.send('action-poweroff'),
  logout: () => ipcRenderer.send('action-logout'),
  getUser: () => ipcRenderer.invoke('get-user'),
  onShow: cb => ipcRenderer.on('animate-in', cb),
  onHide: cb => ipcRenderer.on('animate-out', cb),
  onToolStart: cb => ipcRenderer.on('tool-start', (e, n) => cb(n)),
  onToolOutput: cb => ipcRenderer.on('tool-output', (e, t) => cb(t)),
  onToolEnd: cb => ipcRenderer.on('tool-end', (e, c) => cb(c))
});
